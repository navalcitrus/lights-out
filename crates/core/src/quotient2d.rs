    /// Invariants of the square cell complex on `\mathbb{Z}^2` (vertices at cells, edges between unit neighbours, faces on unit squares) after the quotient.
    #[derive(Debug, PartialEq, Eq)]
    struct Surface {
        euler: i32,
        boundary_components: usize,
        orientable: bool,
    }

    /// `Surface` of an isometry-only quotient, by counting `G`-orbits of vertices, edges and faces.
    fn surface_of(q: &Quotient2D) -> Surface {
        let decomp = AffineDecomp::from_isometries(&q.isometries());
        let l = decomp.lattice;
        let l2 = Lattice::from_vectors(&[(2 * l.b1r, 0), (2 * l.b2r, 2 * l.b2c)]);
        // Canonical orbit key of a doubled point, plus the orientation (det) of the coset rep that reached it.
        let key = |x: (i32, i32)| {
            decomp
                .coset_reps
                .iter()
                .map(|m| {
                    let m2 = LatticeMap::new(
                        m.row_sign,
                        2 * m.row_translate,
                        m.col_sign,
                        2 * m.col_translate,
                    );
                    (l2.reduce(m2.apply(x)), m.row_sign * m.col_sign)
                })
                .min()
                .unwrap()
        };
        let (rows, cols) = (q.rows as i32, q.cols as i32);
        let present = |v: (i32, i32)| decomp.reduce_to_rect(v, rows, cols).is_some();
        let face_present = |f: (i32, i32)| {
            [(-1, -1), (-1, 1), (1, -1), (1, 1)]
                .iter()
                .all(|(dr, dc)| present(((f.0 + dr) / 2, (f.1 + dc) / 2)))
        };

        let mut verts = BTreeSet::new();
        let mut edges = BTreeSet::new();
        let mut boundary: BTreeMap<(i32, i32), [(i32, i32); 2]> = BTreeMap::new();
        let mut faces: BTreeMap<(i32, i32), BTreeSet<i8>> = BTreeMap::new();
        for r in 0..rows {
            for c in 0..cols {
                let v2 = (2 * r, 2 * c);
                verts.insert(key(v2).0);
                for (dr, dc) in [(1, 0), (-1, 0), (0, 1), (0, -1)] {
                    if !present((r + dr, c + dc)) {
                        continue;
                    }
                    let mid = (v2.0 + dr, v2.1 + dc);
                    let e = key(mid).0;
                    edges.insert(e);
                    // The two faces either side of the edge.
                    let sides = [(mid.0 + dc, mid.1 + dr), (mid.0 - dc, mid.1 - dr)];
                    if sides.iter().filter(|&&f| face_present(f)).count() < 2 {
                        let ends = [key(v2).0, key((v2.0 + 2 * dr, v2.1 + 2 * dc)).0];
                        boundary.insert(e, ends);
                    }
                }
                for (dr, dc) in [(-1, -1), (-1, 1), (1, -1), (1, 1)] {
                    let f = (v2.0 + dr, v2.1 + dc);
                    if face_present(f) {
                        let (k, det) = key(f);
                        faces.entry(k).or_default().insert(det);
                    }
                }
            }
        }

        // Boundary edges sharing an endpoint lie on the same boundary circle.
        let ids: BTreeMap<_, _> = boundary.keys().enumerate().map(|(i, e)| (*e, i)).collect();
        let mut by_vertex: BTreeMap<(i32, i32), Vec<CellId>> = BTreeMap::new();
        for (e, ends) in &boundary {
            for v in ends {
                by_vertex.entry(*v).or_default().push(CellId(ids[e]));
            }
        }
        let (_, boundary_components) =
            canonicalize(boundary.len(), &Gluing(by_vertex.into_values().collect()));

        Surface {
            euler: verts.len() as i32 - edges.len() as i32 + faces.len() as i32,
            boundary_components,
            // Seeing one face orbit with both orientations means some deck transformation reverses orientation along a loop in the surface.
            orientable: faces.values().all(|dets| dets.len() == 1),
        }
    }

    const SIZES: [(usize, usize); 6] = [(3, 3), (3, 4), (4, 3), (4, 5), (5, 5), (6, 4)];

    fn assert_surface(name: &str, build: fn(usize, usize) -> Quotient2D, expected: Surface) {
        for (rows, cols) in SIZES {
            let q = build(rows, cols);
            assert_eq!(surface_of(&q), expected, "{name} {rows}x{cols}");
        }
    }

