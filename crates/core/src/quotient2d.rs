    #[test]
    fn sphere_euler_characteristic_is_two() {
        for (rows, cols) in SIZES {
            let q = Quotient2D::sphere(rows, cols);
            let canon = q.collapse_canon();
            let at = |r: usize, c: usize| canon[r * cols + c];
            let v = q.cell_count() as i32;
            let mut e = 0;
            let mut f = 0;
            for r in 0..rows {
                for c in 0..cols {
                    if r + 1 < rows && at(r, c) != at(r + 1, c) {
                        e += 1;
                    }
                    if c + 1 < cols && at(r, c) != at(r, c + 1) {
                        e += 1;
                    }
                    if r + 1 < rows && c + 1 < cols {
                        let corners = [at(r, c), at(r + 1, c), at(r, c + 1), at(r + 1, c + 1)];
                        if corners.iter().any(|&x| x != corners[0]) {
                            f += 1;
                        }
                    }
                }
            }
            assert_eq!(v - e + f, 2, "sphere {rows}x{cols}");
        }
    }

